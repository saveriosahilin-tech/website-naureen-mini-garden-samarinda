create or replace function public.get_garden_rating_summary()
returns table (average_rating numeric, rating_count bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select
    coalesce(round(avg(r.stars)::numeric, 1), 0),
    count(*)::bigint
  from (
    select old_rating.stars::integer as stars
    from public.garden_ratings as old_rating
    where not exists (
      select 1
      from public.garden_reviews as combined_review
      where combined_review.visitor_id = old_rating.visitor_id
        and combined_review.stars is not null
    )
    union all
    select combined_review.stars::integer as stars
    from public.garden_reviews as combined_review
    where combined_review.stars is not null
  ) as r;
$$;

