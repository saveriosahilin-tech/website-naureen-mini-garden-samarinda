create or replace function public.get_garden_reviews(
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 500
)
returns table (
  id bigint,
  visitor_name text,
  stars smallint,
  message text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select r.id, r.visitor_name, r.stars, r.message, r.created_at
  from public.garden_reviews as r
  where p_before_created_at is null
     or (r.created_at, r.id) < (p_before_created_at, p_before_id)
  order by r.created_at desc, r.id desc
  limit least(greatest(coalesce(p_limit, 500), 1), 500);
$$;

create or replace function public.submit_garden_review(
  p_visitor_id uuid,
  p_visitor_name text,
  p_stars integer,
  p_message text
)
returns table (review_saved boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  inserted_count integer;
  clean_name text := btrim(p_visitor_name);
  clean_message text := btrim(p_message);
begin
  if p_visitor_id is null
     or clean_name is null
     or char_length(clean_name) < 1
     or char_length(clean_name) > 40
     or (p_stars is not null and (p_stars < 1 or p_stars > 5))
     or clean_message is null
     or char_length(clean_message) < 10
     or char_length(clean_message) > 500 then
    raise exception 'Nama dan ulasan 10-500 karakter wajib diisi. Rating, jika diisi, harus 1-5 bintang.';
  end if;

  insert into public.garden_reviews (visitor_id, visitor_name, stars, message)
  values (p_visitor_id, clean_name, p_stars, clean_message);

  get diagnostics inserted_count = row_count;
  return query select inserted_count = 1;
end;
$$;

