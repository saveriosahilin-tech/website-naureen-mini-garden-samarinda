create table if not exists public.garden_ratings (
  visitor_id uuid primary key,
  stars smallint not null check (stars between 1 and 5),
  created_at timestamptz not null default now()
);

create table if not exists public.garden_reviews (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  visitor_name text not null,
  stars smallint,
  message text not null,
  created_at timestamptz not null default now(),
  constraint garden_reviews_name_length check (
    char_length(btrim(visitor_name)) between 1 and 40
  ),
  constraint garden_reviews_stars_range check (
    stars is null or stars between 1 and 5
  ),
  constraint garden_reviews_message_length check (
    char_length(btrim(message)) between 10 and 500
  )
);

create index if not exists garden_reviews_created_at_idx
  on public.garden_reviews (created_at desc);

alter table public.garden_reviews
  add column if not exists id bigint generated by default as identity,
  add column if not exists visitor_name text,
  add column if not exists stars smallint;

create index if not exists garden_reviews_created_at_id_idx
  on public.garden_reviews (created_at desc, id desc);

